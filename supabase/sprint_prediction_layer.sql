-- ─────────────────────────────────────────────────────────────────────────────
-- Sprint — Prediction Layer (Unified Session, Tier 2)
-- Run in: Supabase Dashboard → SQL Editor → New Query
-- ─────────────────────────────────────────────────────────────────────────────
--
-- Adds the fields needed for the "lock initial instinct → Quorum predicts →
-- reveal" loop. All new columns are nullable — a session created with the
-- unified session flag OFF (or before this migration) simply never
-- populates them, and every existing read path is unaffected.
--
-- Encryption policy (matching lib/encryption.ts's existing rule — raw user
-- input is encrypted, AI-derived content is not, same as
-- contradictions.principle_text):
--   initial_instinct            — fixed enum, not encrypted (like other enums
--                                 in this schema, e.g. mirror_access status)
--   optimization_priority       — fixed enum, not encrypted, same reasoning
--   quorum_predicted_choice     — AI-derived, not encrypted (same bucket as
--                                 contradictions.principle_text)
--   quorum_prediction_reasoning — AI-derived, not encrypted, same bucket
--   quorum_prediction_used_search — boolean, not encrypted
--   final_decision              — RAW USER INPUT — encrypted, same treatment
--                                 as outcomes.what_decided. Written via
--                                 encrypt() / read via decrypt(), never
--                                 stored or returned in plaintext.
--
-- ── 1. sessions: initial instinct + optimization priority (captured before
--       Quorum says anything — see components/InitialInstinctCapture.tsx) ──

ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS initial_instinct TEXT NULL;

ALTER TABLE public.sessions
  DROP CONSTRAINT IF EXISTS sessions_initial_instinct_check;

ALTER TABLE public.sessions
  ADD CONSTRAINT sessions_initial_instinct_check
    CHECK (initial_instinct IS NULL OR initial_instinct IN ('accept', 'reject', 'unsure'));

ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS optimization_priority TEXT NULL;

ALTER TABLE public.sessions
  DROP CONSTRAINT IF EXISTS sessions_optimization_priority_check;

ALTER TABLE public.sessions
  ADD CONSTRAINT sessions_optimization_priority_check
    CHECK (optimization_priority IS NULL OR optimization_priority IN
      ('career_growth', 'security', 'money', 'time_freedom', 'family', 'other'));

-- ── 2. sessions: Quorum's own prediction of the eventual choice ───────────────
-- Generated by app/api/persona/predict/route.ts — a small, separate call,
-- deliberately NOT part of app/api/persona/route.ts's six-persona orchestration.

ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS quorum_predicted_choice TEXT NULL;

ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS quorum_prediction_reasoning TEXT NULL;

ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS quorum_prediction_used_search BOOLEAN NULL DEFAULT FALSE;

ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS quorum_prediction_generated_at TIMESTAMPTZ NULL;

-- ── 3. sessions: the user's own final decision, captured as its own explicit
--       moment (distinct from initial_instinct, and distinct from the
--       post-hoc "what happened" that OutcomeTracker/outcomes already
--       capture) — see app/api/session/[id]/decide/route.ts ─────────────────

ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS final_decision TEXT NULL;                 -- encrypted (see policy above)

ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS final_decision_locked_at TIMESTAMPTZ NULL;

-- Whether the final decision matched Quorum's prediction. Computed once,
-- at write time, by the decide/ route — not re-derived on every read,
-- since "matched" is a judgment call (string similarity, not equality)
-- that shouldn't silently change if the matching logic is later tuned.
ALTER TABLE public.sessions
  ADD COLUMN IF NOT EXISTS prediction_matched_final BOOLEAN NULL;

CREATE INDEX IF NOT EXISTS idx_sessions_initial_instinct
  ON public.sessions (initial_instinct)
  WHERE initial_instinct IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_sessions_final_decision_locked_at
  ON public.sessions (final_decision_locked_at)
  WHERE final_decision_locked_at IS NOT NULL;

COMMENT ON COLUMN public.sessions.quorum_predicted_choice IS
  'AI-derived — Quorum''s stated guess at what the user will ultimately choose,
   generated before Synthesis is revealed. Not encrypted (AI-derived content,
   same bucket as contradictions.principle_text). Distinct from Synthesis
   (an analysis of the decision) and from initial_instinct (the user''s own
   stated leaning) — see the Unified Session doc for why the three are kept
   as separate states.';
